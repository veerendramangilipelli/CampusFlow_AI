create table public.users (
    id bigint generated by default as identity primary key,
    name varchar(255) not null,
    email varchar(255) not null unique,
    password varchar(255) not null,
    phone varchar(255),
    department varchar(255),
    role varchar(255) not null,
    status varchar(255) not null,
    student_id varchar(255),
    program varchar(255),
    academic_year varchar(255),
    semester integer,
    employee_id varchar(255),
    designation varchar(255),
    placement_department varchar(255),
    created_at timestamp without time zone not null
);

create table public.assignment_submissions (
    id bigint generated by default as identity primary key,
    assignment_id bigint not null,
    student_id bigint not null references public.users (id),
    content text not null,
    submitted_at timestamp without time zone not null,
    constraint uq_assignment_submission_student unique (assignment_id, student_id)
);

alter table public.users enable row level security;
alter table public.assignment_submissions enable row level security;

revoke all on table public.users, public.assignment_submissions from anon, authenticated;
